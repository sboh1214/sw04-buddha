import {
  APPROVAL_REASON_MAX_LENGTH,
  JUDGEMENT_DELAY_REVIEW_MAX_HOURS,
  JUDGEMENT_DELAY_STATUSES,
  type JudgementDelayStatus,
} from '@buddha/shared';
import { sql } from 'drizzle-orm';
import { bigint, check, index, integer, pgTable, text, uuid } from 'drizzle-orm/pg-core';
import { user } from './auth.js';
import { timestampTz } from './columns.js';
import { marketStatusEnum } from './enums.js';
import { marketEvents } from './market-events.js';
import { markets } from './markets.js';

/** A tuple of @buddha/shared as the SQL list a CHECK holds a column to (constants, quoted). */
const sqlList = (values: readonly string[]) =>
  sql.raw(values.map((value) => `'${value}'`).join(', '));

/** A constant of @buddha/shared as the SQL literal a CHECK compares with. */
const literal = (value: number) => sql.raw(String(value));

const STATUSES_SQL = sqlList(JUDGEMENT_DELAY_STATUSES);

/**
 * The bound of the next review time (owner answer 2026-11-03 (1)): JUDGEMENT_DELAY_REVIEW_MAX_DAYS
 * × 24 hours as an interval of hours, which `timestamptz +` adds as elapsed time whatever the
 * session TimeZone — '7 days' would follow a DST change of it.
 */
const REVIEW_MAX_SQL = sql.raw(`interval '${String(JUDGEMENT_DELAY_REVIEW_MAX_HOURS)} hours'`);

/**
 * 판정 지연 기록 (#142, ADR-0106; ADR-0093 decision 1 #173 items 2·7·11·13, decision 3 '#142 지연
 * 사유', the owner's answers of 2026-11-03): one row per record an admin made, alone (#173 item 2:
 * no approval request), of a market that read '판정 지연' on the database clock under the market
 * lock — a CLOSED one past its scheduled judgement, or a PROVISIONAL one a 판정 이의 or a waiting
 * 판정 정정 holds past its 이의 기한 (#173 items 7·11) — written by `recordJudgementDelay`
 * (@buddha/db) after its `judgement_delay_recorded` event, in one transaction. A record changes no
 * `markets` column: no status, no result, no scheduled judgement (#172 item 14), and it never
 * makes a market read '판정 지연'.
 *
 * - `reason`: 지연 사유, one public sentence (decision 3; approvalReasonSchema's 1–500, trimmed),
 *   with no classification (M13 may add one).
 * - `next_review_at`: 다음 검토 시각, in UTC — after the record and at most
 *   JUDGEMENT_DELAY_REVIEW_MAX_DAYS × 24 hours later, on a CLOSED and a PROVISIONAL market alike
 *   (owner answer (1); the CHECK below, the API on the same clock first). Its passing creates
 *   nothing (#173 item 11): the public reads '갱신 대기', the admin detail warns (owner answer (2)).
 * - `market_status` + `judgement_version`: the episode it was recorded in — the market's status
 *   (`closed` or `provisional`, JUDGEMENT_DELAY_STATUSES) and its current judgement version then
 *   (none on CLOSED, the version on PROVISIONAL). The market's current record is the newest of
 *   its current episode (`currentJudgementDelay` of @buddha/shared): a judgement's approval, a
 *   correction's approval or the confirmation leaves the earlier ones history without a write.
 * - `recorded_by`, `recorded_at`, `event_id`: the admin, the instant (the database clock after the
 *   market lock) and the `judgement_delay_recorded` event, one record each. Admins only: the
 *   public answer names nobody and gives no record time (#173 item 13, decision 3).
 *
 * The newest is the greatest `event_id`: a bigserial drawn under the market lock, so the commit
 * order of a market's records. No edit and no withdrawal (owner answer (4)): a change is a new
 * record, the earlier ones its history. Permanent facts (N04 §5): no retention; buddha_app may
 * INSERT and SELECT only, and a trigger refuses an UPDATE or a DELETE whoever writes (migration
 * 0058). The market, the event and the account RESTRICT.
 */
export const marketJudgementDelays = pgTable(
  'market_judgement_delays',
  {
    /** Generated by the writer first, so the event's payload names it. */
    id: uuid().primaryKey().defaultRandom(),
    marketId: uuid()
      .notNull()
      .references(() => markets.id, { onDelete: 'restrict' }),
    reason: text().notNull(),
    nextReviewAt: timestampTz().notNull(),
    marketStatus: marketStatusEnum().$type<JudgementDelayStatus>().notNull(),
    /** Null on CLOSED; the market's `judgement_version` on PROVISIONAL. */
    judgementVersion: integer(),
    recordedBy: text()
      .notNull()
      .references(() => user.id, { onDelete: 'restrict' }),
    /** The database clock after the market lock: `next_review_at` is bounded from it. */
    recordedAt: timestampTz().notNull(),
    eventId: bigint({ mode: 'number' })
      .notNull()
      .unique('market_judgement_delays_event_id_unique')
      .references(() => marketEvents.id, { onDelete: 'restrict' }),
  },
  (t) => [
    check(
      'market_judgement_delays_reason_check',
      sql`btrim(${t.reason}) <> '' AND char_length(${t.reason}) <= ${literal(APPROVAL_REASON_MAX_LENGTH)}`,
    ),
    check(
      'market_judgement_delays_market_status_check',
      sql`${t.marketStatus} IN (${STATUSES_SQL})`,
    ),
    /**
     * The episode: no version on CLOSED (none exists before a judgement), one (≥ 1) on
     * PROVISIONAL; the status itself is the CHECK above's.
     */
    check(
      'market_judgement_delays_judgement_version_check',
      sql`(${t.marketStatus} <> 'closed' OR ${t.judgementVersion} IS NULL) AND (${t.marketStatus} <> 'provisional' OR (${t.judgementVersion} IS NOT NULL AND ${t.judgementVersion} >= 1))`,
    ),
    /** The next review time: after the record, at most the bound later (owner answer (1)). */
    check(
      'market_judgement_delays_next_review_at_check',
      sql`${t.nextReviewAt} > ${t.recordedAt} AND ${t.nextReviewAt} <= ${t.recordedAt} + ${REVIEW_MAX_SQL}`,
    ),
    /**
     * A market's records, the newest first (`readJudgementDelays`, the admin history) and its
     * current one (`readPublicJudgementDelay`, the public detail): by `event_id`.
     */
    index('market_judgement_delays_market_id_event_id_idx').on(t.marketId, t.eventId),
  ],
);
