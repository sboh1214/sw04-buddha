#!/usr/bin/env node
// Regenerates src/generated/schema.ts from the OpenAPI document exported by apps/api.
//
//   pnpm --filter @buddha/api-client generate [path/to/openapi.json]
//
// Input (first match wins): CLI argument, $OPENAPI_JSON, ../../apps/api/openapi.json.
// M0: apps/api does not export a document yet, so the script exits 0 and keeps the
// committed placeholder. The root `api:openapi` script (M3) runs the export, then this.
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const pkgDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const input = resolve(
  pkgDir,
  process.argv[2] ?? process.env.OPENAPI_JSON ?? '../../apps/api/openapi.json',
);
const output = resolve(pkgDir, 'src/generated/schema.ts');

if (!existsSync(input)) {
  console.log(`[api-client] no OpenAPI document at ${input}; keeping existing ${output}`);
  console.log('[api-client] run `pnpm api:openapi` after apps/api can export it (M3)');
  process.exit(0);
}

const { default: openapiTS, astToString } = await import('openapi-typescript');

const ast = await openapiTS(pathToFileURL(input), {
  exportType: true,
  alphabetize: true,
});

const source = relative(pkgDir, input).replaceAll('\\', '/');
const header = [
  '/**',
  ` * This file was auto-generated by openapi-typescript from ${source}.`,
  ' * Do not edit by hand; run `pnpm --filter @buddha/api-client generate`.',
  ' */',
  '',
].join('\n');

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, header + astToString(ast));
console.log(`[api-client] wrote ${output}`);
